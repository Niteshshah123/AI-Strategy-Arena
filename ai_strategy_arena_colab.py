def play(cell,human,algo,state):
    state=state or {"board":EMPTY.copy(),"history":[]}
    b=state["board"].copy();idx=int(cell)-1
    if status(b)[0]!="In progress":
        return [state,"Game over — start a new game.",*board_button_updates(b,human),metrics(Stats(),0,None,None),bar_chart([]),""]
    if next_player(b)!=human:
        return [state,"It is not your turn. The AI moves first when you choose O.",*board_button_updates(b,human),metrics(Stats(),0,None,None),bar_chart([]),""]
    if idx not in moves(b):
        return [state,"That cell is occupied. Choose an empty cell.",*board_button_updates(b,human),metrics(Stats(),0,None,None),bar_chart([]),""]
    state["history"].append(b.copy());b[idx]=human;ai="O" if human=="X" else "X"
    st=Stats();vals=[];ms=0;v=None;move=None
    if status(b)[0]=="In progress":
        move,vals,st,ms,v=search(b,algo,ai)
        if move is not None:b[move]=ai
    s,line=status(b);state.update(board=b,human=human,algo=algo,last_stats=st,last_vals=vals,last_ms=ms,last_v=v,last_move=move)
    msg=f"**{s}.** You played cell {idx+1}."
    if move is not None:msg+=f" {algo} chose cell {move+1} with root utility {v:+.0f}."
    return [state,msg,*board_button_updates(b,human),metrics(st,ms,v,move),bar_chart(vals,[move] if move is not None else []),trace_html(st)]

def reset(human,algo):
    b=EMPTY.copy();history=[];st=Stats();vals=[];ms=0;v=None;move=None
    msg="New game started. Click an empty square on the board to move."
    if human=="O":
        move,vals,st,ms,v=search(b,algo,"X")
        if move is not None:b[move]="X"
        msg=f"New game started. AI (X) opened at cell {move+1}. Your turn as O."
    state={"board":b,"history":history,"human":human,"algo":algo,"last_stats":st,"last_vals":vals,"last_ms":ms,"last_v":v,"last_move":move}
    return [state,msg,*board_button_updates(b,human),metrics(st,ms,v,move),bar_chart(vals,[move] if move is not None else []),trace_html(st)]

def undo(state):
    state=state or {"board":EMPTY.copy(),"history":[]}
    if not state.get("history"):
        b=state["board"]
        return [state,"No move to undo yet.",*board_button_updates(b,state.get("human","X")),metrics(Stats(),0,None,None),bar_chart([]),trace_html(Stats())]
    state["board"]=state["history"].pop();st=Stats()
    # If the player is O, undoing the first player move restores the empty board.
    state.update(last_stats=st,last_vals=[],last_ms=0,last_v=None,last_move=None)
    b=state["board"]
    return [state,"Move undone.",*board_button_updates(b,state.get("human","X")),metrics(st,0,None,None),bar_chart([]),trace_html(st)]

def aivai(scenario,xalgo,oalgo,plies):
    b=EXAMPLES[scenario].copy();logs=[]
    for ply in range(int(plies)):
        if status(b)[0]!="In progress":break
        p=next_player(b);algo=xalgo if p=="X" else oalgo
        m,vals,st,ms,v=search(b,algo,p)
        if m is None:break
        b[m]=p;logs.append(f"| {ply+1} | {p} | {algo} | {m+1} | {v:+.0f} | {st.nodes} | {st.cutoffs} |")
    s,line=status(b)
